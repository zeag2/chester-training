// Builds supabase/deploy/send-push.ts: the send-push Edge Function as ONE file (meds.ts + core.ts + index.ts, the
// relative imports dropped), for pasting into Supabase → Edge Functions → Deploy a new function → Via editor, which
// can't follow `../_shared/` imports. Run: node scripts/send-push-one-file.mjs  (src/lib/sendpushfile.test.ts checks
// the committed copy is current).
import { readFileSync, writeFileSync } from 'node:fs';

export function oneFile(read = (p) => readFileSync(p, 'utf8')) {
  const strip = (s) => s.replace(/^import [^;]*from '\.{1,2}\/[^']*';\n/gm, '');
  const meds = read('supabase/functions/_shared/meds.ts');
  const core = read('supabase/functions/send-push/core.ts');
  const index = read('supabase/functions/send-push/index.ts');
  return `// GENERATED by scripts/send-push-one-file.mjs from supabase/functions/send-push/{index,core}.ts and _shared/meds.ts.
// Don't edit: change those files and run the script. Paste this whole file into the Supabase dashboard editor
// (function name: send-push), then turn OFF "Verify JWT" for it (the cron sends x-cron-key, not a sign-in).

${strip(index)}
// ---- core.ts ----
${strip(core)}
// ---- _shared/meds.ts ----
${strip(meds)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('supabase/deploy/send-push.ts', oneFile());
  console.log('wrote supabase/deploy/send-push.ts');
}
